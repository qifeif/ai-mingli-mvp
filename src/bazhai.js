// ---------- 工具 ----------
function reduceToDigit(n) {
  n = Math.abs(n);
  while (n > 9) n = String(n).split('').reduce((a, c) => a + +c, 0);
  return n === 0 ? 9 : n;
}

/** 从 datetime 取「立春换年」后的出生年(立春 ≈ 2/4 近似) */
function liChunYear(datetime) {
  const m = String(datetime).match(/(\d{4})-(\d{1,2})-(\d{1,2})/);
  if (!m) throw new Error('datetime 格式应为 "YYYY-MM-DD ..."');
  let [Y, M, D] = [+m[1], +m[2], +m[3]];
  if (M < 2 || (M === 2 && D <= 4)) Y -= 1; // 立春前归上一年
  return Y;
}

// ---------- 本命卦 ----------
/**
 * @param {object} input { gender:'男'|'女', datetime?:string, year?:number }
 * @returns {object} 命卦详情
 */
export function computeMingGua(input) {
  const gender = input.gender;
  const year = input.year ?? liChunYear(input.datetime);
  const Z = reduceToDigit(String(year).split('').reduce((a, c) => a + +c, 0));

  let num;
  if (year >= 2000) {
    // 2000 年起口诀:男 = 9 − Z,女 = Z + 6
    num = gender === '男' ? 9 - Z : Z + 6;
  } else {
    // 2000 年前口诀:男 = 11 − Z,女 = Z + 4
    num = gender === '男' ? 11 - Z : Z + 4;
  }
  if (num > 9) num -= 9;
  if (num <= 0) num += 9;

  // 寄宫:男逢 5 → 坤(2),女逢 5 → 艮(8)
  const raw = num;
  if (num === 5) num = gender === '男' ? 2 : 8;

  const 卦 = NUM_TO_GUA[num];
  const info = GUA_INFO[卦];
  return {
    卦,
    卦数: info.数,
    原始数: raw,
    五行: info.五行,
    本位方位: info.方位,
    命组: info.命组,
    寄宫: raw === 5,
    白话: info.命组 === '东四命'
      ? `你是「${卦}命 · 东四命」,吉方集中在 东 / 东南 / 南 / 北,本位在${info.方位}。`
      : `你是「${卦}命 · 西四命」,吉方集中在 西 / 西北 / 西南 / 东北,本位在${info.方位}。`,
    备注: '本命卦含立春换年(≈2/4 近似)与 2000 年前后口诀分支,正式请以《地脉道》原文复核。',
  };
}

// ---------- 八方位吉凶 ----------
/** @param {string} 卦 本命卦名(已处理寄宫) */
export function eightMansions(卦) {
  const i = GUA_ORDER.indexOf(卦);
  const map = {};
  map[GUA_DIR[卦]] = '伏位';
  VERSE[卦].forEach((ch, k) => {
    const palace = GUA_ORDER[(i + 1 + k) % 8];
    map[GUA_DIR[palace]] = STAR_CHAR[ch];
  });
  return DISPLAY_ORDER.map((方位) => {
    const 星 = map[方位];
    return { 方位, 星, ...STAR_META[星] };
  });
}

// ---------- 推荐 ----------
/**
 * 综合本命卦 + 诉求,给出方位推荐
 * @returns {{命卦, 八方位, 吉方:Array, 凶方:Array, 首选:object, 诉求方位:object, 摘要:string}}
 */
export function recommendDirections(input) {
  const 命卦 = computeMingGua(input);
  const dirs = eightMansions(命卦.卦);
  const 吉方 = dirs.filter((d) => STAR_META[d.星].good).sort((a, b) => b.rank - a.rank);
  const 凶方 = dirs.filter((d) => !STAR_META[d.星].good).sort((a, b) => a.rank - b.rank);

  const goal = GOALS.find((g) => g.key === input.goal) || GOALS[0];
  const 诉求方位 = dirs.find((d) => d.星 === goal.star);
  const 首选 = 吉方[0]; // rank 最高的吉方(通常生气)

  const 摘要 = `${命卦.卦}命(${命卦.命组})。卧室首选 ${诉求方位.方位}方(${诉求方位.星}·${goal.名}),` +
    `次选 ${首选.方位}方(${首选.星});务必避开 ${凶方[0].方位}方(${凶方[0].星})作长期卧室。`;

  return { 命卦, 诉求: goal, 八方位: dirs, 吉方, 凶方, 首选, 诉求方位, 摘要 };
}
